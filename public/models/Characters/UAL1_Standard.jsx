const LANDING_LOCOMOTION_WEIGHT = 0.55
const LANDING_BLEND_DURATION = 0.18
const NAMEPLATE_DISTANCE = 2.5

function CharacterNameplate({ label, characterRef }) {
  const characterPosition = React.useRef(new Vector3())
  const playerNearbyRef = React.useRef(false)
  const [playerNearby, setPlayerNearby] = React.useState(false)

  useFrame(() => {
    if (!characterRef.current) return

    characterRef.current.getWorldPosition(characterPosition.current)
    const [playerX, playerY, playerZ] = useGameStore.getState().location
    const { x, y, z } = characterPosition.current
    const isNearby =
      (playerX - x) ** 2 + (playerY - y) ** 2 + (playerZ - z) ** 2 <=
      NAMEPLATE_DISTANCE ** 2

    if (isNearby !== playerNearbyRef.current) {
      playerNearbyRef.current = isNearby
      setPlayerNearby(isNearby)
    }
  })

  if (!playerNearby) return null

  return (
    <Billboard position={[0, 2.5, 0]} follow>
      <Text
        anchorX="center"
        anchorY="middle"
        color="white"
        fontSize={0.25}
        outlineColor="#1a1a1a"
        outlineWidth={0.02}
      >
        {label}
      </Text>
    </Billboard>
  )
}

